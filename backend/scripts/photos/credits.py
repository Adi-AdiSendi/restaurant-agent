"""One credit line per photo, for docs/photo-credits.md (ADR 0024)."""

from scripts.photos.openverse import Candidate

_LICENCES = {"cc0": "CC0", "pdm": "Public Domain Mark", "by": "CC BY", "by-sa": "CC BY-SA"}

HEADER = """# Photo credits

Dish and restaurant photos come from [Openverse](https://openverse.org) under
licences that allow changes and commercial use (ADR 0024). Each photo shows a
similar dish, not this app's own, and was cropped to 4:3 and resized. A photo
under CC BY-SA stays under CC BY-SA. Generated by
`backend/scripts/photos/import_photos.py`; do not edit by hand.

"""


def licence_name(candidate: Candidate) -> str:
    name = _LICENCES.get(candidate.license, candidate.license.upper())
    version = candidate.license_version
    return f"{name} {version}" if version and candidate.license not in {"pdm"} else name


def credit_line(label: str, photo: str, candidate: Candidate) -> str:
    """`label` names the dish for people; `photo` is the file name the tests match."""
    title = candidate.title.strip() or "Untitled"
    creator = candidate.creator or "an unknown creator"
    licence = licence_name(candidate)
    if candidate.license_url:
        licence = f"[{licence}]({candidate.license_url})"
    return (
        f'- **{label}** (`{photo}`): "{title}" by {creator}, {licence}, '
        f"[source]({candidate.foreign_landing_url})."
    )
